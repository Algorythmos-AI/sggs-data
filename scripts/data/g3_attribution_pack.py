#!/usr/bin/env python3
"""Evidence for the attribution and structure fixes held for the G3 scholar (dataset 1.3.0).

    python3 scripts/data/g3_attribution_pack.py PRE.sqlite POST.sqlite database.sqlite OUTDIR

Writes OUTDIR/evidence.md (the printed lines, the current and new dataset values, and the ShabadOS
4.8.7 record for every line an item touches), OUTDIR/changes.csv (every changed `lines` field) and
OUTDIR/downstream.md (every count a consumer will see move), and renders OUTDIR/README.md from
OUTDIR/README.template.md: {gID} becomes line ID's Gurmukhi and {lastID} the last number printed in its
markers. Every Gurmukhi run left in the README must occur in the corpus, or the script fails. Every Gurmukhi quote is copied from the
database by this script, never typed. ShabadOS is evidence only: lines are aligned on first letters
as pipeline/crosscheck_authors.py aligns them, and nothing from it reaches the corpus.
"""
import csv, difflib, hashlib, json, os, re, sqlite3, sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'pipeline'))
import crosscheck_authors as X  # noqa: E402

COLS = ['ang', 'comp_id', 'line_no', 'is_header', 'section', 'author', 'source_category']
TYPES = {1: 'Manglacharan (invocation)', 2: 'Sirlekh (heading)', 3: 'Rahao', 4: 'Pankti (verse)'}

ITEMS = [
    ('A-07', 'Bhagat Surdas Ji, Ang 1253', [(53924, 53943)]),
    ('A-08', 'Salok Bhagat Kabir Ji and Salok Sheikh Farid Ji as their own sections, Angs 1363-1385',
     [(58273, 58274), (58295, 58298), (58789, 58792), (59086, 59088)]),
    ('A-10', 'Composition 2749, Ang 695', [(30064, 30066), (30079, 30084), (30090, 30093), (30097, 30101), (30108, 30110)]),
    ('A-11', 'The Bhagat-run heading on Ang 524 (and its twin on Ang 323)', [(23469, 23472), (14770, 14773)]),
]


def con(p):
    c = sqlite3.connect(f'file:{p}?mode=ro', uri=True)
    c.row_factory = sqlite3.Row
    return c


def sos_rows(sos_path, angs):
    """ShabadOS lines for the given Angs: key, shabad, sttm id, writer, line type."""
    db = sqlite3.connect(f'file:{sos_path}?mode=ro', uri=True)
    out = defaultdict(list)
    for ang, lid, fl, shabad, sttm, writer, typ in db.execute(
            f"""SELECT l.source_page, l.id, l.first_letters, l.shabad_id, s.sttm_id, w.name_english, l.type_id
                FROM lines l JOIN shabads s ON s.id = l.shabad_id JOIN writers w ON w.id = s.writer_id
                WHERE s.source_id = 1 AND l.source_page IN ({','.join('?' * len(angs))})
                ORDER BY l.order_id""", sorted(angs)):
        out[ang].append({'key': X.key_sos(fl or ''), 'line': lid, 'shabad': shabad, 'sttm': sttm,
                         'writer': X.WRITER.get(writer, writer), 'type': TYPES.get(typ, typ)})
    return out


def align(post, sos, angs):
    """our id -> ShabadOS record, aligned Ang by Ang on first letters."""
    m = {}
    for ang in angs:
        ours = [dict(r) for r in post.execute('SELECT id, fl_g, text FROM lines WHERE ang = ? ORDER BY id', (ang,))]
        theirs = sos.get(ang, [])
        sm = difflib.SequenceMatcher(a=[X.key_ours(r) for r in ours], b=[t['key'] for t in theirs], autojunk=False)
        for a, b, n in sm.get_matching_blocks():
            for k in range(n):
                m[ours[a + k]['id']] = theirs[b + k]
    return m


def digest(c, table):
    """(sha256 over every row in a stable order, row count) -- order-independent like verify_regroup's."""
    rows = sorted(repr(tuple(r)) for r in c.execute(f'SELECT * FROM "{table}"'))
    return hashlib.sha256('\n'.join(rows).encode('utf-8')).hexdigest(), len(rows)


def cell(v):
    return '—' if v is None or v == '' else str(v).replace('|', '\\|')


def evidence(pre, post, sos_path, out):
    ids = [i for _, _, rs in ITEMS for a, b in rs for i in range(a, b + 1)]
    angs = {r[0] for r in post.execute(f"SELECT DISTINCT ang FROM lines WHERE id IN ({','.join(map(str, ids))})")}
    sos = align(post, sos_rows(sos_path, angs), angs)
    lines = ['# Evidence: the printed lines, the dataset, and ShabadOS 4.8.7', '',
             'Generated by `scripts/data/g3_attribution_pack.py`. Every Gurmukhi line is copied from the database; '
             'none is typed. **1.2.0** is the dataset the app ships today; **1.3.0** is this PR. A cell in bold '
             'changes. ShabadOS columns come from the pinned ShabadOS database (release 4.8.7, '
             '`pipeline/shabados.SHA256SUMS`), aligned by first letters; `sttm` is the SikhiToTheMax/BaniDB shabad id '
             'that ShabadOS records. "Sirlekh" is ShabadOS\'s own line type for a heading.', '']
    for item, title, ranges in ITEMS:
        lines += [f'## {item} · {title}', '',
                  '| id | Ang | line, verbatim | comp 1.2.0 → 1.3.0 | heading? | section 1.2.0 → 1.3.0 | author 1.2.0 → 1.3.0 | ShabadOS shabad (sttm) | ShabadOS writer | ShabadOS line type |',
                  '|---|---|---|---|---|---|---|---|---|---|']
        for a, b in ranges:
            for i in range(a, b + 1):
                x = pre.execute('SELECT * FROM lines WHERE id = ?', (i,)).fetchone()
                y = post.execute('SELECT * FROM lines WHERE id = ?', (i,)).fetchone()
                assert x['gurmukhi'] == y['gurmukhi'] and x['text'] == y['text']

                def pair(c, fmt=cell):
                    if x[c] == y[c]:
                        return fmt(x[c])
                    return f'**{fmt(x[c])} → {fmt(y[c])}**'
                s = sos.get(i)
                lines.append('| ' + ' | '.join([
                    str(i), str(y['ang']), y['gurmukhi'], pair('comp_id'),
                    pair('is_header', lambda v: 'yes' if v else 'no'), pair('section'), pair('author'),
                    f"{s['shabad']} ({s['sttm']})" if s else 'not aligned',
                    s['writer'] if s else '—', s['type'] if s else '—']) + ' |')
            lines.append('| | | … | | | | | | | |')
        lines.append('')
    open(os.path.join(out, 'evidence.md'), 'w', encoding='utf-8').write('\n'.join(lines).rstrip('\n') + '\n')


def changes(pre, post, out):
    cols = [r[1] for r in pre.execute('PRAGMA table_info(lines)')]
    rows = []
    for x, y in zip(pre.execute('SELECT * FROM lines ORDER BY id'), post.execute('SELECT * FROM lines ORDER BY id')):
        for c in cols:
            if x[c] != y[c]:
                rows.append([x['id'], x['ang'], c, x[c], y[c], y['gurmukhi']])
    with open(os.path.join(out, 'changes.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['id', 'ang', 'field', 'dataset_1_2_0', 'dataset_1_3_0', 'gurmukhi'])
        w.writerows(rows)
    return Counter(r[2] for r in rows)


def downstream(pre, post, out, changed):
    def q(c, sql):
        return c.execute(sql).fetchall()

    md = ['# What moves downstream (dataset 1.2.0 → 1.3.0)', '',
          'Generated by `scripts/data/g3_attribution_pack.py`. For the platform `dataset.lock.json` bump and the '
          'iOS vendor sync: every count below is read from the two databases.', '',
          '## `lines` fields', '', '| field | lines changed |', '|---|---|']
    md += [f'| `{k}` | {v} |' for k, v in sorted(changed.items())]
    md += ['', 'No other `lines` column changed (`scripts/data/diff_scripture.py`).', '']

    one = lambda c, s: c.execute(s).fetchone()[0]
    md += ['## Compositions', '', '| | 1.2.0 | 1.3.0 |', '|---|---|---|']
    for label, sql in [('distinct `comp_id`', 'SELECT COUNT(DISTINCT comp_id) FROM lines'),
                       ('`max(comp_id)`', 'SELECT MAX(comp_id) FROM lines'),
                       ('heading lines (`is_header = 1`)', 'SELECT SUM(is_header) FROM lines'),
                       ('verse lines (`is_header = 0`)', 'SELECT COUNT(*) - SUM(is_header) FROM lines')]:
        md.append(f'| {label} | {one(pre, sql):,} | {one(post, sql):,} |')
    md += ['', 'Compositions whose line set changed:', '', '| comp_id | lines 1.2.0 | lines 1.3.0 | opens with |',
           '|---|---|---|---|']
    a = dict(q(pre, 'SELECT comp_id, COUNT(*) FROM lines GROUP BY comp_id'))
    b = dict(q(post, 'SELECT comp_id, COUNT(*) FROM lines GROUP BY comp_id'))
    for c in sorted(set(a) | set(b)):
        if a.get(c) != b.get(c):
            first = post.execute('SELECT gurmukhi FROM lines WHERE comp_id = ? ORDER BY id LIMIT 1', (c,)).fetchone()
            md.append(f'| {c} | {a.get(c, "—")} | {b.get(c, "—")} | {first[0] if first else "—"} |')

    md += ['', '## Sections (`sections` table)', '', '| section | 1.2.0 Angs · lines | 1.3.0 Angs · lines |', '|---|---|---|']
    sa = {r[0]: r[1:] for r in q(pre, 'SELECT name, first_ang, last_ang, n_lines FROM sections')}
    sb = {r[0]: r[1:] for r in q(post, 'SELECT name, first_ang, last_ang, n_lines FROM sections')}
    fmt = lambda v: f'{v[0]}–{v[1]} · {v[2]}' if v else '—'
    for s in sorted(set(sa) | set(sb), key=lambda s: (sb.get(s) or sa.get(s))[0]):
        if sa.get(s) != sb.get(s):
            md.append(f'| {s} | {fmt(sa.get(s))} | {fmt(sb.get(s))} |')

    md += ['', '## Voices (`lines.author`)', '',
           f"Distinct authors: **{one(pre, 'SELECT COUNT(DISTINCT author) FROM lines')}** → "
           f"**{one(post, 'SELECT COUNT(DISTINCT author) FROM lines')}**.", '',
           '| author | lines 1.2.0 | lines 1.3.0 | verses 1.2.0 | verses 1.3.0 |', '|---|---|---|---|---|']
    la = {r[0]: r[1:] for r in q(pre, 'SELECT author, COUNT(*), SUM(is_header = 0) FROM lines GROUP BY author')}
    lb = {r[0]: r[1:] for r in q(post, 'SELECT author, COUNT(*), SUM(is_header = 0) FROM lines GROUP BY author')}
    for au in sorted(set(la) | set(lb), key=str):
        if la.get(au) != lb.get(au):
            x, y = la.get(au, (0, 0)), lb.get(au, (0, 0))
            md.append(f'| {au} | {x[0]} | {y[0]} | {x[1]} | {y[1]} |')

    md += ['', 'Voices per raag (distinct authors with at least one line in the raag):', '',
           '| raag | 1.2.0 | 1.3.0 | joins | leaves |', '|---|---|---|---|---|']
    va, vb = defaultdict(set), defaultdict(set)
    for r, au in q(pre, 'SELECT DISTINCT raag, author FROM lines WHERE raag IS NOT NULL'):
        va[r].add(au)
    for r, au in q(post, 'SELECT DISTINCT raag, author FROM lines WHERE raag IS NOT NULL'):
        vb[r].add(au)
    for r in sorted(set(va) | set(vb)):
        if va[r] != vb[r]:
            md.append(f'| {r} | {len(va[r])} | {len(vb[r])} | {", ".join(sorted(map(str, vb[r] - va[r]))) or "—"} | '
                      f'{", ".join(sorted(map(str, va[r] - vb[r]))) or "—"} |')

    md += ['', '`raags.n_shabads` (compositions with a heading in the raag\'s span):', '',
           '| raag | 1.2.0 | 1.3.0 |', '|---|---|---|']
    ra_, rb_ = dict(q(pre, 'SELECT name, n_shabads FROM raags')), dict(q(post, 'SELECT name, n_shabads FROM raags'))
    md += [f'| {r} | {ra_.get(r)} | {rb_.get(r)} |' for r in sorted(set(ra_) | set(rb_)) if ra_.get(r) != rb_.get(r)]

    wa = dict(q(pre, 'SELECT * FROM word_freq'))
    wb = dict(q(post, 'SELECT * FROM word_freq'))
    md += ['', '`word_freq` (verse words only, so a line that becomes a heading leaves it):', '',
           '| word | 1.2.0 | 1.3.0 |', '|---|---|---|']
    md += [f'| {w} | {wa.get(w, 0)} | {wb.get(w, 0)} |' for w in sorted(set(wa) | set(wb)) if wa.get(w) != wb.get(w)]

    md += ['', '## Every table whose content differs', '',
           'By content hash over all rows (`scripts/data/compare_builds.py` gives the same list).', '',
           '| table | rows 1.2.0 | rows 1.3.0 |', '|---|---|---|']
    for (t,) in q(post, "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name"):
        if t.startswith('sqlite_') or any(t.endswith(s) for s in ('_data', '_idx', '_docsize', '_config', '_content')):
            continue
        try:
            ha, ra = digest(pre, t)
        except sqlite3.OperationalError:
            ha, ra = None, None
        hb, rb = digest(post, t)
        if ha != hb:
            md.append(f'| `{t}` | {ra if ra is not None else "—"} | {rb} |')
    open(os.path.join(out, 'downstream.md'), 'w', encoding='utf-8').write('\n'.join(md).rstrip('\n') + '\n')


def readme(post, out):
    tpl = os.path.join(out, 'README.template.md')
    if not os.path.exists(tpl):
        return
    g = lambda i: post.execute('SELECT gurmukhi FROM lines WHERE id = ?', (int(i),)).fetchone()[0]

    def last(i):
        m = json.loads(post.execute('SELECT markers FROM lines WHERE id = ?', (int(i),)).fetchone()[0])
        return [x for x in m if re.fullmatch('[੦-੯]+', x)][-1]
    s = open(tpl, encoding='utf-8').read()
    s = re.sub(r'\{g(\d+)\}', lambda m: g(m.group(1)), s)
    s = re.sub(r'\{last(\d+)\}', lambda m: last(m.group(1)), s)
    known = '\n'.join(r[0] for r in post.execute('SELECT gurmukhi FROM lines UNION SELECT name FROM sections'))
    runs = re.findall(r'[\u0A00-\u0A7F][\u0A00-\u0A7F ॥…]*[\u0A00-\u0A7F॥]|[\u0A00-\u0A7F]', s)
    bad = sorted({p.strip() for r in runs for p in r.split('…') if p.strip() and p.strip() not in known})
    if bad:
        sys.exit(f'README: Gurmukhi not found in the corpus: {bad}')
    open(os.path.join(out, 'README.md'), 'w', encoding='utf-8').write(s)


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    pre_p, post_p, sos_p, out = sys.argv[1:]
    os.makedirs(out, exist_ok=True)
    pre, post = con(pre_p), con(post_p)
    evidence(pre, post, sos_p, out)
    changed = changes(pre, post, out)
    downstream(pre, post, out, changed)
    readme(post, out)
    print(f'wrote {out}/evidence.md, changes.csv, downstream.md ({sum(changed.values())} field changes: {dict(changed)})')


if __name__ == '__main__':
    main()
