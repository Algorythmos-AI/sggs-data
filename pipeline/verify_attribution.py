# -*- coding: utf-8 -*-
"""Gate for the attribution post-pass (pipeline/attribution.py).

  python3 pipeline/verify_attribution.py <pre.jsonl> <post.jsonl> [--oracle database.sqlite]
                                         [--review-dir validation/attribution-review]

Fails unless:
  1. pre and post have the same line ids and every field except `author` is identical
     (scripture, comp_id, line_no, is_header, markers ... untouched);
  2. the pass is idempotent on post (re-applying it changes nothing);
  3. with --oracle: every line that still disagrees with the independent edition lies inside
     an attribution_ledger.json entry (proposed for review, or kept on printed evidence).
With --review-dir, writes the human review pack: every re-attributed composition with its
printed heading, first and last verse (Gurmukhi, verbatim) and the evidence used.
"""
import sys, os, json, argparse, collections, csv
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import attribution  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument('pre'); ap.add_argument('post')
ap.add_argument('--oracle'); ap.add_argument('--review-dir')
a = ap.parse_args()
load = lambda p: [json.loads(l) for l in open(p, encoding='utf-8')]
pre, post = load(a.pre), load(a.post)
fail = []

# 1 -- only `author` may differ
if [r['id'] for r in pre] != [r['id'] for r in post]:
    fail.append('line ids differ')
changed = []
for x, y in zip(pre, post):
    for k in set(x) | set(y):
        if k != 'author' and x.get(k) != y.get(k):
            fail.append(f"id {x['id']}: field {k!r} changed"); break
    if x.get('author') != y.get('author'):
        changed.append((x, y))
print(f'1. only `author` changed: {"OK" if not fail else "FAIL"} ({len(changed)} lines re-attributed)')

# 2 -- idempotent
ledger = attribution.load_ledger(os.path.join(HERE, 'attribution_ledger.json'))
again = [dict(r) for r in post]
log, flags = attribution.apply(again, ledger)
if log:
    fail.append(f'not idempotent: {len(log)} further changes (first id {log[0]["id"]})')
print(f'2. idempotent: {"OK" if not log else "FAIL"}; {len(flags)} flagged for review')

# 3 -- every residual disagreement is documented
residual = []
if a.oracle:
    import attribution_audit as A
    theirs, _, matched = A.align(post, A.load_oracle(a.oracle))
    covered = [(e['start_id'], e['end_id'], e['entry'], e['status']) for e in ledger]
    for r, t in zip(post, theirs):
        if r['is_header'] or t is None or t == r['author']:
            continue
        hit = next((c for c in covered if c[0] <= r['id'] <= c[1]), None)
        residual.append((r, t, hit))
    bad = [x for x in residual if x[2] is None]
    for r, t, _ in bad[:20]:
        print(f"   UNDOCUMENTED id {r['id']} ang {r['ang']}: ours={r['author']} oracle={t} | {r['gurmukhi'][:50]}")
    if bad:
        fail.append(f'{len(bad)} disagreements with the independent edition are not in the ledger')
    by = collections.Counter(h[2] for _, _, h in residual if h)
    print(f'3. residual vs independent edition: {len(residual)} lines, all documented: '
          f'{"OK" if not bad else "FAIL"} {dict(by)}')

# review pack
if a.review_dir:
    os.makedirs(a.review_dir, exist_ok=True)
    comps = collections.OrderedDict()
    for x, y in changed:
        comps.setdefault((x['comp_id'], x.get('author'), y.get('author')), []).append(y)
    by_comp = collections.defaultdict(list)
    for r in post:
        by_comp[r['comp_id']].append(r)
    with open(os.path.join(a.review_dir, 'changes.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f)
        w.writerow(['id', 'ang', 'comp_id', 'from', 'to', 'gurmukhi'])
        for x, y in changed:
            w.writerow([x['id'], x['ang'], x['comp_id'], x.get('author') or '', y.get('author') or '', y['gurmukhi']])
    md = ['# Attribution review pack', '',
          'Every composition whose `author` changed, with the evidence printed in the Granth. '
          'Text is verbatim from the corpus; only the author tag changed. Generated by '
          '`pipeline/verify_attribution.py`.', '',
          f'Lines re-attributed: **{len(changed)}** in **{len(comps)}** composition runs.', '',
          '| Ang | Composition | Was | Now | Heading | First verse | Signed / last verse |',
          '|---|---|---|---|---|---|---|']
    for (cid, fr, to), rows in comps.items():
        allrows = by_comp[cid]
        heads = ' / '.join(r['gurmukhi'] for r in allrows if r['is_header']) or '—'
        body = [r for r in rows if not r['is_header']] or rows
        md.append(f"| {rows[0]['ang']}–{rows[-1]['ang']} | {cid} ({len(rows)} lines) | {fr or '—'} | {to} | "
                  f"{heads} | {body[0]['gurmukhi']} | {body[-1]['gurmukhi']} |")
    md += ['', '## Decisions waiting on a scholar (ledger status `proposed`, nothing changed)', '']
    for e in ledger:
        if e['status'] == 'proposed':
            md.append(f"- **{e['entry']}** (ids {e['start_id']}–{e['end_id']}): {e['reason']}")
    md += ['', '## Kept on printed evidence although an independent edition differs', '']
    for e in ledger:
        if e['status'] == 'keep':
            md.append(f"- **{e['entry']}**: {e['reason']}")
    md += ['', '## Saloks signed by another Bhagat inside a collection (flagged)', '']
    for fl in flags:
        md.append(f"- Ang {fl['ang']} (id {fl['id']}): in {fl['collection']}'s saloks, signed by "
                  f"{fl['signed']}: {fl['text']}")
    open(os.path.join(a.review_dir, 'README.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    print(f'review pack: {a.review_dir}/README.md, changes.csv')

if fail:
    print('ATTRIBUTION GATE FAIL'); [print('  -', f) for f in fail[:20]]; sys.exit(1)
print('ATTRIBUTION GATE PASS')
